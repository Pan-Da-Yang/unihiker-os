# 去重并保持顺序
seen = set()
chars = []
for c in COMMON_CHARS:
    if c not in seen and not c.isspace():
        seen.add(c)
        chars.append(c)

py_list = pinyin(chars, style=Style.NORMAL, errors="ignore", strict=False)
# 输出格式：{拼音: [字1, 字2, ...]}，方便输入法按拼音查找候选
from collections import OrderedDict
data = OrderedDict()
for ch, py in zip(chars, py_list):
    p = py[0] if py and py[0] else ""
    if p:
        data.setdefault(p, []).append(ch)

out = os.path.join(_HERE, "pinyin_dict.json")
with open(out, "w", encoding="utf-8") as f:
    json.dump(data, f, ensure_ascii=False, indent=0)

